/**
 * Generate `src/test/baseline-0.7.0/typeCompat.baseline.test.ts` from the
 * verbatim 0.7.0 root declarations beside it (`api-0.7.0.d.ts`).
 *
 * @remarks
 * For every 0.7.0 export the generated test asserts that the name still
 * exists and that its 0.7.0 type is assignable to and from the current one.
 * Run with `npm run generate:type-compat`; never edit the output by hand.
 *
 * @module
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

import { format, resolveConfig } from 'prettier';

const dir = join(import.meta.dirname, '..', 'src', 'test', 'baseline-0.7.0');
const out = join(dir, 'typeCompat.baseline.test.ts');
const declarations = readFileSync(join(dir, 'api-0.7.0.d.ts'), 'utf8');

/** Names listed in the first export block matching `pattern`. */
function exportBlock(pattern: RegExp): string[] {
  const match = pattern.exec(declarations);
  if (!match) throw new Error(`export block missing: ${String(pattern)}`);
  return match[1]
    .split(',')
    .map((name) => name.trim())
    .filter(Boolean);
}

const values = exportBlock(/^export \{([\s\S]*?)\};?$/m);
const types = exportBlock(/^export type \{([\s\S]*?)\};?$/m);

/**
 * Zod schemas that gained optional fields in 0.8.0 (spec 5.7, 5.8): their
 * schema objects differ, so they are compared by input and output instead.
 */
const SCHEMAS = [
  'jeevesComponentDescriptorSchema',
  'pluginToolsetOptionsSchema',
];

/** Generic types without defaults, with the arguments to compare them at. */
const TYPE_ARGS: Record<string, [string, string]> = {
  ParsedArgs: ['Old.ArgSpec', 'Current.ArgSpec'],
  ResolvedValue: ['string', 'string'],
};

const mutual = (old: string, current: string) =>
  `    expectTypeOf<Mutual<${old}, ${current}>>().toEqualTypeOf<true>();`;

const lines = [
  '/**',
  ' * 0.7.0 type compatibility for the root entry point (spec \u00a75 Verification,',
  ' * dev-plan step 16). Generated by `npm run generate:type-compat` from',
  ' * `api-0.7.0.d.ts` (the 0.7.0 built declarations, kept verbatim beside this',
  ' * test): every 0.7.0 export still exists, and its 0.7.0 type is assignable',
  ' * to and from the current one. Compared by type, not by declaration text.',
  ' * Never edit by hand.',
  ' *',
  ' * @module',
  ' */',
  '',
  "import { describe, expect, expectTypeOf, it } from 'vitest';",
  "import type { z } from 'zod';",
  '',
  "import type * as Current from '../../index.js';",
  "import type * as Old from './api-0.7.0.js';",
  '',
  '/** `true` when A and B are assignable to each other. */',
  'type Mutual<A, B> = [A] extends [B] ? ([B] extends [A] ? true : false) : false;',
  '',
  "describe('0.7.0 baseline: root types', () => {",
  "  it('every 0.7.0 export still exists, with a mutually assignable type', async () => {",
  "    const current = await import('../../index.js');",
  `    expect(Object.keys(current)).toEqual(expect.arrayContaining(${JSON.stringify(values)}));`,
  ...values
    .filter((name) => !SCHEMAS.includes(name))
    .map((name) =>
      mutual(`(typeof Old)['${name}']`, `(typeof Current)['${name}']`),
    ),
  '    // Schemas that gained optional fields: 0.8.0 adds optional fields to these Zod schemas (spec 5.7, 5.8), so the',
  '    // schema objects differ; what callers pass and get back stays compatible.',
  ...SCHEMAS.flatMap((name) =>
    ['input', 'output'].map((io) =>
      mutual(
        `z.${io}<(typeof Old)['${name}']>`,
        `z.${io}<(typeof Current)['${name}']>`,
      ),
    ),
  ),
  '    // Every 0.7.0 type export.',
  ...types.map((name) => {
    const args = TYPE_ARGS[name] as [string, string] | undefined;
    return args
      ? mutual(`Old.${name}<${args[0]}>`, `Current.${name}<${args[1]}>`)
      : mutual(`Old.${name}`, `Current.${name}`);
  }),
  '  });',
  '});',
  '',
];

const options = await resolveConfig(out);
writeFileSync(
  out,
  await format(lines.join('\n'), { ...options, filepath: out }),
);
console.log(`values ${String(values.length)}, types ${String(types.length)}`);
